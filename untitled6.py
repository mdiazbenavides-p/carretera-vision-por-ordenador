from imageai.Detection import ObjectDetection

# Instantiating the object detection class
detector = ObjectDetection()

# Setting a path to the YOLOv3 model
model_path = "/content/yolov3.pt"

# Installing the YOLOv3 model and setting a path to the weights file
detector.setModelTypeAsYOLOv3()
detector.setModelPath(model_path)

# Loading the model
detector.loadModel()

# A list of all object the model knows about
detector.CustomObjects()

# Reconocer imágenes en la imagen seleccionada con una probabilidad de al menos el 30% y guardarlas en un nuevo archivo.
detections = detector.detectObjectsFromImage(
    input_image="/content/input_image.jpg",
    output_image_path="output_image.jpg",
    minimum_percentage_probability=30)

for eachObject in detections:
    print(eachObject["name"] , " : ", eachObject["percentage_probability"], " : ", eachObject["box_points"] )
    print("--------------------------------")

